from typing import Any

from django.db import transaction
from django.utils import timezone

from cameras.models import Camera, CameraStatus
from monitoring.models import (
    AlertSeverity,
    CameraAlert,
    CameraAlertType,
)

@transaction.atomic
def update_camera_status(
    camera: Camera,
    new_status: str,
    received_at=None,
) -> Camera:
    """
    Update camera status and last_seen.

    A valid MQTT camera message proves that the camera
    is communicating, so camera status becomes ONLINE.
    """

    if received_at is None:
        received_at = timezone.now()

    if new_status not in CameraStatus.values:
        raise ValueError(
            f"Invalid camera status: {new_status}"
        )

    camera.status = new_status
    camera.last_seen = received_at

    camera.save(
        update_fields=[
            "status",
            "last_seen",
            "updated_at",
        ]
    )

    return camera


def get_camera(
    device,
    camera_identifier: str,
    channel: int,
) -> Camera | None:
    """
    Resolve a camera belonging to the specified Edge device.
    """

    try:
        return Camera.objects.get(
            device=device,
            camera_identifier=camera_identifier,
            channel=channel,
            active=True,
        )

    except Camera.DoesNotExist:
        return None


def create_camera_alert(
    camera: Camera,
    alert_type: str,
    message: str,
    payload: dict[str, Any],
    severity: str = AlertSeverity.WARNING,
) -> CameraAlert:
    """
    Create a camera alert.

    If an active alert with the same type already exists,
    reuse it instead of creating duplicates.
    """

    existing_alert = CameraAlert.objects.filter(
        camera=camera,
        alert_type=alert_type,
        active=True,
    ).first()

    if existing_alert:
        return existing_alert

    return CameraAlert.objects.create(
        camera=camera,
        alert_type=alert_type,
        severity=severity,
        message=message,
        raw_payload=payload,
    )


@transaction.atomic
def process_camera_alert(
    camera: Camera,
    payload: dict[str, Any],
    received_at=None,
) -> CameraAlert:
    """
    Process an alert generated by a camera.

    Receiving the message proves the camera is communicating,
    therefore the camera becomes ONLINE.
    """

    if received_at is None:
        received_at = timezone.now()

    update_camera_status(
        camera=camera,
        new_status=CameraStatus.ONLINE,
        received_at=received_at,
    )

    action_code = payload.get(
        "action_code",
        "UNKNOWN",
    )

    class_label = payload.get(
        "class_label",
        "unknown",
    )

    confidence = payload.get(
        "confidence",
    )

    message = (
        f"Camera '{camera.name}' detected "
        f"'{class_label}' "
        f"(action={action_code}"
    )

    if confidence is not None:
        message += f", confidence={confidence}"

    message += ")."

    return create_camera_alert(
        camera=camera,
        alert_type=CameraAlertType.CAMERA_ALERT,
        message=message,
        payload=payload,
        severity=AlertSeverity.WARNING,
    )


@transaction.atomic
def process_camera_event(
    camera: Camera,
    payload: dict[str, Any],
    action_code: str,
    received_at=None,
) -> CameraAlert | None:
    """
    Process a camera event.

    Events prove camera communication but do not necessarily
    create an alert.
    """

    if received_at is None:
        received_at = timezone.now()

    update_camera_status(
        camera=camera,
        new_status=CameraStatus.ONLINE,
        received_at=received_at,
    )

    return None


@transaction.atomic
def process_camera_error(
    camera: Camera,
    payload: dict[str, Any],
    received_at=None,
) -> CameraAlert:
    """
    Process an error reported by a camera.

    The camera remains ONLINE because it successfully
    communicated the error.
    """

    if received_at is None:
        received_at = timezone.now()

    update_camera_status(
        camera=camera,
        new_status=CameraStatus.ONLINE,
        received_at=received_at,
    )

    error_message = payload.get(
        "message",
        payload.get(
            "error",
            "Camera reported an error.",
        ),
    )

    return create_camera_alert(
        camera=camera,
        alert_type=CameraAlertType.CAMERA_ERROR,
        message=(
            f"Camera '{camera.name}' reported an error: "
            f"{error_message}"
        ),
        payload=payload,
        severity=AlertSeverity.WARNING,
    )